// 按科目提供 WhisperHint + QuizHint 默认模板。admin 在课程表单点"套用科目模板"
// 后，两个 textarea 会被填上对应模板内容，可继续微调。
//
// 设计原则：
// 1. 模板默认就是「能直接用」的状态——不留 [占位符]（admin 不删的话 whisper 会
//    把方括号文字当术语念出来，反而干扰）。admin 想补充口音/特定术语再手动加。
// 2. WhisperHint 控制在 240 字符内（transcriber.py 会截断，长了浪费）。
// 3. QuizHint 里的「术语字典」聚焦 whisper 真常常错的同音字，不堆砌所有术语。
//
// 后端把 whisper_hint/quiz_hint 存进单一 JSON 列（Course.AIConfigJSON），加新配置
// 项不必改 DB schema——这里加字段时同步扩 backend model.AIConfig 即可。

export interface AiHintTemplate {
  whisperHint: string;
  quizHint: string;
}

// 按科目 label 匹配模板。label 来自后端 Subject.Label（如"数学""象棋""语文"）。
// 匹配大小写不敏感、trim 后包含即命中（"小学数学"也能匹配"数学"）。
// 无匹配返回 null（调用方据此提示"该科目暂无模板"）。
export function getSubjectTemplate(subjectLabel: string): AiHintTemplate | null {
  const label = (subjectLabel ?? '').trim().toLowerCase();
  if (!label) return null;
  // 按优先级匹配：ORDERED_KEYS 定义了命中顺序（特殊/长的关键词在前，
  // 避免被宽泛规则抢匹配，如"道德与法治"必须先于"法"）。
  for (const key of ORDERED_KEYS) {
    if (label.includes(key)) {
      const canonical = ALIASES[key] ?? key;
      return TEMPLATES[canonical];
    }
  }
  return null;
}

